for (const locale of ["zh-Hant", "zh-Hans"] as const) {
  const table = scenarioCopy[locale];
  for (const item of scenarios) {
    if (!table[item.slug]) {
      throw new Error(`Missing ${locale} scenario i18n for ${item.slug}`);
    }
  }
  if (Object.keys(table).length !== scenarios.length) {
    throw new Error(
      `${locale} scenario i18n has ${Object.keys(table).length} slugs, expected ${scenarios.length}`,
    );
  }
}

export function localizeScenario(item: Scenario, locale: Locale): Scenario {
  if (locale === "en" || locale === "ja") return item;
  const localized = scenarioCopy[locale][item.slug];
  if (!localized) return item;
  return {
    ...item,
    title: localized.title,
    short: localized.short,
    oneLiner: localized.oneLiner,
    does: localized.does,
    who: localized.who,
    startWith: localized.startWith,
  };
}
